"""
dbt Transformation Layer Generator.

Generates production-grade dbt SQL models (staging, intermediate, marts),
schema.yml test definitions, and documentation for Lakehouse workloads.
"""

import os 
from typing import Any ,Dict ,List ,Optional 
import pandas as pd 


class DbtTransformGenerator :
    """
    Generates dbt transformation models and schema test suites.
    """

    def __init__ (self ,project_name :str ="innovate_lakehouse"):
        self .project_name =project_name 

    def generate_staging_model (self ,table_name :str ,df :pd .DataFrame ,primary_key :Optional [str ]=None )->str :
        """
        Generate staging model SQL (stg_{table_name}.sql).
        Performs explicit casting, trimming, and NULL sanitization.
        """
        columns_sql =[]
        for col in df .columns :
            dtype =str (df [col ].dtype )
            clean_col =col .strip ().lower ().replace (" ","_")

            if "int"in dtype :
                sql_type ="INTEGER"
                expr =f"CAST({col } AS {sql_type }) AS {clean_col }"
            elif "float"in dtype :
                sql_type ="DOUBLE PRECISION"
                expr =f"CAST({col } AS {sql_type }) AS {clean_col }"
            elif "bool"in dtype :
                sql_type ="BOOLEAN"
                expr =f"CAST({col } AS {sql_type }) AS {clean_col }"
            elif "datetime"in dtype :
                sql_type ="TIMESTAMP"
                expr =f"CAST({col } AS {sql_type }) AS {clean_col }"
            else :
                expr =f"TRIM(NULLIF(CAST({col } AS VARCHAR), '')) AS {clean_col }"

            columns_sql .append (f"        {expr }")

        cols_block =(chr (44 )+chr (10 )).join (columns_sql )
        sql =f"""-- Staging Model: stg_{table_name }.sql
-- Generated by innovATE Lakehouse Governance Engine
{{{{ config(
    materialized='view',
    tags=['ai_ready', 'staging', 'governed']
) }}}}

WITH source_data AS (
    SELECT * FROM {{{{ source('lakehouse_raw', '{table_name }') }}}}
),

renamed_and_cast AS (
    SELECT
{cols_block }
    FROM source_data
)

SELECT * FROM renamed_and_cast
"""
        return sql 

    def generate_schema_yml (
    self ,
    table_name :str ,
    df :pd .DataFrame ,
    primary_key :Optional [str ]=None ,
    non_null_cols :Optional [List [str ]]=None 
    )->str :
        """
        Generate dbt schema.yml containing assertions and Great Expectations macros.
        """
        p_key =primary_key or (df .columns [0 ]if len (df .columns )>0 else "id")
        nn_cols =set (non_null_cols or [])

        columns_yaml =[]
        for col in df .columns :
            clean_col =col .strip ().lower ().replace (" ","_")
            tests =[]

            if clean_col ==p_key or col ==primary_key :
                tests .append ("        - unique")
                tests .append ("        - not_null")
            elif col in nn_cols :
                tests .append ("        - not_null")

            test_block =chr (10 )+chr (10 ).join (tests )if tests else " []"

            columns_yaml .append (f"""      - name: {clean_col }
        description: "AI-governed feature: {clean_col }"
        tests:{test_block }""")

        cols_str =chr (10 ).join (columns_yaml )

        yml =f"""version: 2

models:
  - name: stg_{table_name }
    description: "Staging model for {table_name } with verified data types and NULL hygiene."
    tests:
      - dbt_expectations.expect_table_row_count_to_be_between:
          min_value: 1
    columns:
{cols_str }
"""
        return yml 

    def generate_mart_model (self ,table_name :str ,primary_key :str ="id")->str :
        """Generate production AI feature mart model."""
        return f"""-- Mart Model: fct_{table_name }_ai_features.sql
-- Production AI-Ready Feature Store View
{{{{ config(
    materialized='table',
    file_format='delta',
    tags=['feature_store', 'ai_training_ready']
) }}}}

WITH staging AS (
    SELECT * FROM {{{{ ref('stg_{table_name }') }}}}
)

SELECT
    *,
    CURRENT_TIMESTAMP() AS feature_engineered_at,
    'CERTIFIED_AI_READY' AS quality_audit_status
FROM staging
WHERE {primary_key } IS NOT NULL
"""
